import ludo_game as L
import os
import time

os.environ["SDL_VIDEODRIVER"] = "dummy"
os.environ["SDL_AUDIODRIVER"] = "dummy"

# Set up the UI for an entirely automated game
ui = L.LudoUI(opponents=3, speed=1000.0, seed=42)
ui.set_brain("ANN")

print("Starting automated game simulation...")
last_log_idx = 0

# Run the loop continuously until the game is over
while not ui.over:
    ui.update()
    # Print new log messages as they appear
    while len(ui.log) > last_log_idx:
        print(ui.log[last_log_idx][0])
        last_log_idx += 1
    time.sleep(0.001)

w = ui.g.winner
print(f"\n*** Game Over! Winner is Player {w} ({ui.pname(w)}) ***")